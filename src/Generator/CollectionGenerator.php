<?php

declare(strict_types=1);

namespace Cg\Cms\Generator;

use Illuminate\Support\Str;
use RuntimeException;

/**
 * Plans everything a new collection needs, without writing anything.
 *
 * A routed collection gets: its schema entry, a controller, two routes, an
 * index and a show template, and a test that proves the pages render and
 * drafts stay hidden. A routeless one (data used by other pages, like proof
 * metrics) gets the schema entry only.
 *
 * Templates come from stubs. The package's are plain; an application puts
 * its own in `stubs/cms/` to make generated pages match its design, and the
 * same goes for the per-field snippets in `stubs/cms/fields/`.
 */
final class CollectionGenerator
{
    /**
     * @param  array<int, FieldSpec>  $fields
     */
    public function __construct(
        private readonly string $handle,
        private readonly string $label,
        private readonly array $fields,
        private readonly ?string $routeBase,
        private readonly string $schemaPath,
        private readonly string $routesPath,
    ) {}

    /** @return array<int, PlannedFile> */
    public function plan(): array
    {
        $files = [new PlannedFile($this->schemaPath, $this->schemaWithCollection(), 'Add the collection to the schema', insert: true)];

        if ($this->routeBase === null) {
            return $files;
        }

        $class = $this->className();
        $views = $this->viewDirectory();

        return [
            ...$files,
            new PlannedFile(app_path("Http/Controllers/{$class}.php"), $this->render('controller', $this->controllerReplacements()), 'Controller for the index and show pages'),
            new PlannedFile($this->routesPath, $this->routesWithCollection(), 'Routes for '.$this->routeBase.' and '.$this->routeBase.'/{slug}', insert: true),
            new PlannedFile(resource_path("views/{$views}/index.blade.php"), $this->render('index.blade', $this->viewReplacements()), 'Index page template'),
            new PlannedFile(resource_path("views/{$views}/show.blade.php"), $this->render('show.blade', $this->viewReplacements()), 'Single page template'),
            new PlannedFile(base_path('tests/Feature/'.Str::studly($this->handle).'PagesTest.php'), $this->render('test', $this->testReplacements()), 'Test that the pages render and drafts stay hidden'),
        ];
    }

    /** The schema code for this collection, as it will be inserted. */
    public function schemaCode(): string
    {
        $lines = [];
        $lines[] = "    Collection::make('{$this->handle}')";
        $lines[] = "        ->label('".addslashes($this->label)."')";

        if ($this->routeBase !== null) {
            $lines[] = "        ->route('{$this->routeBase}/{slug}')";
            $lines[] = "        ->indexRoute('{$this->routeBase}')";
            $lines[] = "        ->orderBy('published_at', 'desc')";
            $lines[] = "        ->seoTitle('{title} | ".addslashes($this->label)." | {site}')";

            if ($this->summaryField() !== null) {
                $lines[] = "        ->seoDescriptionFrom('{$this->summaryField()}')";
            }
        } else {
            $lines[] = "        ->orderBy('title', 'asc')";
        }

        $fields = ["Field::text('title')->required()->maxLength(120)"];

        if ($this->routeBase !== null) {
            $fields[] = "Field::slug('slug')->from('title')";
        }

        foreach ($this->fields as $field) {
            $fields[] = $field->toPhp();
        }

        if ($this->routeBase !== null) {
            $fields[] = "Field::datetime('published_at')->nullable()";
        }

        $fields[] = "Field::select('status')->options(['draft', 'published'])->default('draft')";

        if ($this->routeBase !== null) {
            $fields[] = 'Field::seo()';
        }

        $lines[] = '        ->fields([';

        foreach ($fields as $field) {
            $lines[] = "            {$field},";
        }

        $lines[] = '        ]),';

        $date = now()->toDateString();
        $title = "{$this->handle}, generated by cms:collection on {$date}";

        return "    /*\n    |".str_repeat('-', 75)."\n    | {$title}\n    |".str_repeat('-', 75)."\n    */\n\n".implode("\n", $lines)."\n";
    }

    private function schemaWithCollection(): string
    {
        $source = (string) file_get_contents($this->schemaPath);
        $position = strrpos($source, '];');

        if ($position === false) {
            throw new RuntimeException("Could not find the end of the schema array in {$this->schemaPath}.");
        }

        return rtrim(substr($source, 0, $position))."\n\n".$this->schemaCode()."\n".substr($source, $position);
    }

    private function routesWithCollection(): string
    {
        $source = (string) file_get_contents($this->routesPath);
        $class = $this->className();
        $import = "use App\\Http\\Controllers\\{$class};";
        $name = $this->routeName();

        if (! str_contains($source, $import)) {
            // After the last controller import, or after the opening tag.
            if (preg_match_all('/^use App\\\\Http\\\\Controllers\\\\[^;]+;$/m', $source, $matches, PREG_OFFSET_CAPTURE) > 0) {
                $last = end($matches[0]);
                $at = $last[1] + strlen($last[0]);
                $source = substr($source, 0, $at)."\n".$import.substr($source, $at);
            } else {
                $source = preg_replace('/^(<\?php\s*(declare\(strict_types=1\);\s*)?)/', "$1\n{$import}\n", $source, 1) ?? $source;
            }
        }

        return rtrim($source)."\n\n"
            ."// {$this->label}, generated by cms:collection.\n"
            ."Route::get('{$this->routeBase}', [{$class}::class, 'index'])->name('{$name}.index');\n"
            ."Route::get('{$this->routeBase}/{slug}', [{$class}::class, 'show'])->name('{$name}.show');\n";
    }

    /** @return array<string, string> */
    private function controllerReplacements(): array
    {
        $loads = [];
        $registers = [];

        foreach ($this->relations() as $field) {
            $value = $field->many
                ? "(array) \$entry->value('{$field->name}', [])"
                : "array_filter([(string) \$entry->value('{$field->name}', '')])";

            $loads[] = "            '{$field->name}' => Entry::query()->collection('{$field->target}')->published()->whereIn('slug', {$value})->get(),";
            $registers[] = "        \$this->cacheContext->registerCollection('{$field->target}');";
        }

        return [
            'class' => $this->className(),
            'handle' => $this->handle,
            'label' => $this->label,
            'view' => $this->viewDirectory(),
            'routeBase' => (string) $this->routeBase,
            'summary' => $this->summaryField() ?? '',
            'relations' => $loads === [] ? '' : implode("\n", $loads),
            'registerRelations' => $registers === [] ? '' : implode("\n", array_unique($registers))."\n",
        ];
    }

    /** @return array<string, string> */
    private function viewReplacements(): array
    {
        $body = [];

        foreach ($this->fields as $field) {
            $body[] = $this->render('fields/'.$field->type, [
                'name' => $field->name,
                'label' => Str::headline($field->name),
                'routeName' => $field->target === null ? '' : $field->target,
            ]);
        }

        return [
            'handle' => $this->handle,
            'label' => $this->label,
            'singular' => Str::singular($this->label),
            'routeBase' => (string) $this->routeBase,
            'fields' => rtrim(implode("\n", array_filter($body, fn (string $snippet): bool => trim($snippet) !== ''))),
        ];
    }

    /** @return array<string, string> */
    private function testReplacements(): array
    {
        return [
            'handle' => $this->handle,
            'studly' => Str::studly($this->handle),
            'label' => $this->label,
            'routeBase' => (string) $this->routeBase,
        ];
    }

    /**
     * Fill a stub. Placeholders are `[[name]]`, so they never collide with
     * Blade's own braces.
     *
     * @param  array<string, string>  $replacements
     */
    private function render(string $stub, array $replacements): string
    {
        $contents = (string) file_get_contents(self::stubPath($stub));

        foreach ($replacements as $key => $value) {
            $contents = str_replace("[[{$key}]]", $value, $contents);
        }

        // A placeholder whose value was empty leaves a blank line behind.
        return (string) preg_replace("/^[ \t]*\n(?=[ \t]*\n)/m", '', $contents);
    }

    /** The application's stub if it has one, otherwise the package's. */
    public static function stubPath(string $stub): string
    {
        $custom = base_path("stubs/cms/{$stub}.stub");

        return is_file($custom) ? $custom : dirname(__DIR__, 2)."/stubs/{$stub}.stub";
    }

    /** @return array<int, FieldSpec> */
    private function relations(): array
    {
        return array_values(array_filter($this->fields, fn (FieldSpec $field): bool => $field->type === 'relation'));
    }

    /** The first textarea, used as the index summary and SEO description. */
    private function summaryField(): ?string
    {
        foreach ($this->fields as $field) {
            if ($field->type === 'textarea') {
                return $field->name;
            }
        }

        return null;
    }

    public function className(): string
    {
        return Str::studly($this->handle).'Controller';
    }

    private function viewDirectory(): string
    {
        return Str::kebab(Str::camel(Str::plural($this->handle)));
    }

    private function routeName(): string
    {
        return Str::kebab(Str::camel(Str::plural($this->handle)));
    }
}
