<?php

declare(strict_types=1);

namespace Cg\Cms\Console;

use Cg\Cms\Models\Redirect;
use Illuminate\Console\Command;

/**
 * Exports the redirect table as an nginx map.
 *
 * An accelerator, never a dependency. The site resolves every one of these rules
 * correctly in PHP already (see NotFoundHandler), so a box with no root access,
 * a container with a read-only filesystem, or a stale map all behave correctly.
 * What the map buys is answering a legacy URL without starting PHP at all, which
 * on a 1 vCPU box is the difference between a redirect costing nothing and a
 * redirect costing a worker.
 *
 * The database stays the source of truth. That is the inversion compared to the
 * current stack, where the nginx config is the source of truth and the only way
 * to add a redirect is to edit a file on the server and reload.
 *
 * Consumed with:
 *
 *     map $request_uri $cg_redirect {
 *         default "";
 *         include /var/www/site/shared/redirects.map;
 *     }
 *
 *     if ($cg_redirect != "") { return 301 $cg_redirect; }
 */
final class ExportNginxRedirectsCommand extends Command
{
    protected $signature = 'cms:export-nginx-redirects
        {--path= : Where to write. Defaults to storage/app/redirects.map}
        {--stdout : Print instead of writing, for piping into a deploy step}';

    protected $description = 'Export redirects as an nginx map file';

    public function handle(): int
    {
        $redirects = Redirect::query()
            ->orderByDesc('priority')
            ->orderBy('id')
            ->get();

        $lines = [
            '# Generated by cms:export-nginx-redirects. Do not edit.',
            '# The database is the source of truth; this file is an accelerator.',
            '# Rules: '.$redirects->count(),
            '',
        ];

        $skipped = [];

        foreach ($redirects as $redirect) {
            $line = $this->lineFor($redirect);

            if ($line === null) {
                $skipped[] = $redirect->from;

                continue;
            }

            $lines[] = $line;
        }

        $contents = implode("\n", $lines)."\n";

        if ($this->option('stdout')) {
            $this->line($contents);

            return self::SUCCESS;
        }

        $path = $this->option('path') ?? storage_path('app/redirects.map');
        $directory = dirname((string) $path);

        if (! is_dir($directory)) {
            mkdir($directory, 0o755, recursive: true);
        }

        file_put_contents($path, $contents);

        $this->components->info(sprintf('Wrote %d rule(s) to %s', $redirects->count() - count($skipped), $path));

        if ($skipped !== []) {
            // These still work, they just work in PHP. Saying so is the
            // difference between a known trade and a mystery.
            $this->components->warn(sprintf(
                '%d rule(s) could not be expressed as a map entry and are left to the application: %s',
                count($skipped),
                implode(', ', array_slice($skipped, 0, 5)).(count($skipped) > 5 ? ' and more' : ''),
            ));
        }

        $this->newLine();
        $this->components->bulletList([
            'Reload nginx after copying this into place. A map is read at config load.',
            'Only 301 and 302 belong in a map. Other statuses stay in the application.',
        ]);

        return self::SUCCESS;
    }

    /**
     * One map entry, or null if the rule cannot be expressed as one.
     *
     * nginx map keys are literal strings, a `~` prefixed regex, or a `*.` style
     * wildcard that only applies to hostnames. A prefix rule therefore becomes
     * an anchored regex with a capture, which is the only form that can carry
     * the rest of the path through to the target.
     */
    private function lineFor(Redirect $redirect): ?string
    {
        // A map can only produce a single status via the `return` it feeds, so
        // anything that is not a plain permanent or temporary redirect has to
        // be resolved by the application where the status is known.
        if (! in_array($redirect->status, [301, 302], true)) {
            return null;
        }

        // `force` rules must beat a real route, and a map consulted before
        // try_files cannot know whether a route exists. Those stay in PHP.
        if ($redirect->force) {
            return null;
        }

        $from = $redirect->from;
        $to = $redirect->to;

        return match ($redirect->match_type) {
            'exact' => $this->quote($from).' '.$this->quote($to).';',

            // No delimiter passed to preg_quote: an nginx regex has none, so
            // escaping the slashes would emit \/ everywhere. Valid PCRE, but
            // noise in a file a human has to read during a cutover.
            'prefix' => '~'.$this->quote('^'.preg_quote(rtrim($from, '/')).'(/.*)?$')
                .' '.$this->quote(rtrim($to, '/').'$1').';',

            'regex' => '~'.$this->quote($from).' '.$this->quote($to).';',

            default => null,
        };
    }

    /**
     * Quote a map value.
     *
     * nginx treats several characters as significant in an unquoted token, and
     * a URL containing a `{` or a `;` would end the directive early and stop
     * nginx from starting at all. Quoting everything removes the question.
     */
    private function quote(string $value): string
    {
        return '"'.str_replace(['\\', '"'], ['\\\\', '\\"'], $value).'"';
    }
}
